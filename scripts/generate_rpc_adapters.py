#!/usr/bin/env python3
"""Generate typed Kitex client facades and business dispatch from RPC IDLs."""
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[1]
DOMAINS = ('user', 'content', 'media', 'interaction', 'feed', 'message', 'search', 'recommend', 'assistant', 'behavior', 'review', 'ad')
HEADER = '// Code generated by scripts/generate_rpc_adapters.py. DO NOT EDIT.\n\n'

def snake(s):
    return re.sub(r'(?<!^)(?=[A-Z])', '_', s).lower()

def generate(domain):
    proto = (ROOT / f'proto/{domain}/{domain}.proto').read_text()
    service = re.search(r'^service (\w+)', proto, re.M)[1]
    pkg = service.lower()
    messages = re.findall(r'^message (\w+)', proto, re.M)
    methods = re.findall(r'rpc\s+(\w+)\((stream\s+)?(\w+)\)\s+returns\s+\((stream\s+)?(\w+)\)', proto)
    clientdir = ROOT / f'app/{domain}/rpc/{pkg}'
    clientdir.mkdir(exist_ok=True)
    # The facade keeps domain APIs independent of framework call construction.
    parts = [HEADER, f'package {pkg}\n\n', 'import (\n', '\t"context"\n\t"io"\n', f'\tpb "esx/kitex_gen/{domain}"\n', f'\tnative "esx/kitex_gen/{domain}/{pkg}"\n', '\t"esx/pkg/rpcx"\n', '\t"github.com/cloudwego/kitex/client/callopt"\n', *(['\t"github.com/cloudwego/kitex/pkg/streaming"\n'] if any(cs or ss for _, cs, _, ss, _ in methods) else []), ')\n']
    parts += [f'type {name} = pb.{name}\n' for name in messages]
    parts += [f'type {service} = native.Client\n', f'type client struct {{ native.Client }}\n', f'func New{service}(spec rpcx.Client) {service} {{ raw:=native.MustNewClient(spec.ServiceName(),spec.Options()...);spec.Track(raw.(io.Closer));return &client{{Client:raw}} }}\n']
    for name, cs, req, ss, resp in methods:
        if cs or ss:
            st = f'{service}_{name}Client'
            parts += [f'type {st} = native.{st}\n', f'type {name}Stream struct {{ native.{st} }}\n', f'func(s *{name}Stream)DoFinish(err error){{streaming.FinishStream(s.{st},err)}}\n']
            arg = '' if cs else f', req *pb.{req}'
            callarg = '' if cs else ', req'
            parts += [f'func(c *client){name}(ctx context.Context{arg},opts ...callopt.Option)({st},error){{s,e:=c.Client.{name}(ctx{callarg},opts...);if e!=nil{{return nil,rpcx.FromTransportError(e)}};return &{name}Stream{{s}},nil}}\n']
            if cs:
                parts += [f'func(s *{name}Stream) Send(v *pb.{req})error{{return rpcx.FromTransportError(s.{st}.Send(v))}}\n', f'func(s *{name}Stream) CloseAndRecv()(*pb.{resp},error){{v,e:=s.{st}.CloseAndRecv();streaming.FinishStream(s.{st},e);return v,rpcx.FromTransportError(e)}}\n']
            if ss:
                parts += [f'func(s *{name}Stream) Recv()(*pb.{resp},error){{v,e:=s.{st}.Recv();return v,rpcx.FromTransportError(e)}}\n']
        else:
            parts += [f'func(c *client){name}(ctx context.Context,req *pb.{req},opts ...callopt.Option)(*pb.{resp},error){{v,e:=c.Client.{name}(ctx,req,opts...);return v,rpcx.FromTransportError(e)}}\n']
    clientfile = clientdir / f'{snake(service)}.go'
    clientfile.write_text(''.join(parts))
    parts = [HEADER, 'package server\n\nimport (\n\t"context"\n', f'\tpb "esx/kitex_gen/{domain}"\n', f'\t"esx/app/{domain}/rpc/internal/logic"\n\t"esx/app/{domain}/rpc/internal/svc"\n)\n', f'type {service}Server struct{{svcCtx *svc.ServiceContext}}\n', f'func New{service}Server(ctx *svc.ServiceContext)*{service}Server{{return &{service}Server{{svcCtx:ctx}}}}\n']
    for name, cs, req, ss, resp in methods:
        if cs:
            parts += [f'func(s *{service}Server){name}(stream pb.{service}_{name}Server)error{{return logic.New{name}Logic(stream.Context(),s.svcCtx).{name}(stream)}}\n']
        elif ss:
            parts += [f'func(s *{service}Server){name}(req *pb.{req},stream pb.{service}_{name}Server)error{{return logic.New{name}Logic(stream.Context(),s.svcCtx).{name}(req,stream)}}\n']
        else:
            parts += [f'func(s *{service}Server){name}(ctx context.Context,req *pb.{req})(*pb.{resp},error){{return logic.New{name}Logic(ctx,s.svcCtx).{name}(req)}}\n']
    closefile = ROOT / f'kitex_gen/{domain}/{pkg}/lifecycle.go'
    closefile.write_text(HEADER + f'package {pkg}\nfunc(c *k{service}Client)Close()error{{return c.kClient.c.(interface{{Close()error}}).Close()}}\n')
    subprocess.run(['gofmt','-w',str(closefile)],check=True)
    serverfile = ROOT / f'app/{domain}/rpc/internal/server/{snake(service)}_server.go'
    serverfile.write_text(''.join(parts))
    subprocess.run(['gofmt','-w',str(clientfile),str(serverfile)],check=True)

if __name__ == '__main__':
    for domain in DOMAINS:
        generate(domain)
