#!/usr/bin/env python3
"""Generate Gateway DTOs and Hertz registration from the OpenAPI contract."""
from pathlib import Path
import re
import subprocess
import yaml
from openapi_spec_validator import validate

ROOT = Path(__file__).resolve().parents[1]
HEADER = '// Code generated by scripts/generate_gateway.py from openapi.yaml. DO NOT EDIT.\n\n'

class ContractLoader(yaml.SafeLoader):
    pass


def unique_mapping(loader, node, deep=False):
    result = {}
    for key_node, value_node in node.value:
        key = loader.construct_object(key_node, deep=deep)
        if key in result:
            raise ValueError(f'duplicate OpenAPI key: {key}')
        result[key] = loader.construct_object(value_node, deep=deep)
    return result


ContractLoader.add_constructor(yaml.resolver.BaseResolver.DEFAULT_MAPPING_TAG, unique_mapping)


def generate():
    spec = yaml.load((ROOT / 'app/gateway/openapi.yaml').read_text(), Loader=ContractLoader)
    if spec.get('openapi') != '3.0.3':
        raise ValueError('Gateway requires OpenAPI 3.0.3')
    validate(spec)
    schemas = spec['components']['schemas']
    lines = [HEADER, 'package types\n\n']
    for name, definition in sorted(schemas.items()):
        if name == 'PublicError':
            continue
        lines.append(f'type {name} struct {{\n')
        required = definition.get('required', [])
        for field, prop in definition.get('properties', {}).items():
            typename, goname = prop['x-go-type'], prop['x-go-name']
            location = prop['x-binding']
            tag = 'form' if location == 'query' else location
            options = [field]
            if field not in required:
                options.append('optional')
            if 'default' in prop:
                options.append('default=' + str(prop['default']).lower())
            lines.append(f'\t{goname} {typename} `{tag}:"{",".join(options)}"`\n')
        lines.append('}\n\n')
    output = ROOT / 'app/gateway/internal/types/types.go'
    # Previous generation split DTOs by group; this generator owns the directory.
    for old in output.parent.glob('*.go'):
        if old.name != output.name and old.read_text().startswith('// Code generated'):
            old.unlink()
    output.write_text(''.join(lines))
    operations = []
    ids = set()
    for path, item in spec['paths'].items():
        for method, operation in item.items():
            if method not in ('get', 'post', 'put', 'patch', 'delete'):
                raise ValueError(f'unsupported OpenAPI operation {method}')
            name = operation['operationId']
            if name in ids:
                raise ValueError(f'duplicate operationId {name}')
            ids.add(name)
            group = operation['x-handler-group']
            operations.append((path, method, operation, group))
    groups = sorted({g for _, _, _, g in operations if g})
    lines = [HEADER, 'package handler\n\nimport (\n', '\t"esx/app/gateway/internal/svc"\n', '\t"esx/pkg/httpx"\n', '\t"github.com/cloudwego/hertz/pkg/app/server"\n']
    lines += [f'\t{g.replace("_", "")} "esx/app/gateway/internal/handler/{g}"\n' for g in groups]
    lines += [')\n\nfunc RegisterHandlers(server *server.Hertz, serverCtx *svc.ServiceContext) {\n']
    for path, method, operation, group in operations:
        chain = [f'httpx.RoutePolicy({operation["x-timeout-ms"]}, {operation["x-max-body-bytes"]}, {str(operation.get("x-sse", False)).lower()})']
        if operation.get('x-optional-auth'):
            chain.append('serverCtx.OptionalAuth')
        elif operation.get('security'):
            chain.append('serverCtx.RequiredAuth')
        if operation.get('x-accepted'):
            chain.append('serverCtx.BehaviorAccepted')
        prefix = group.replace('_', '') + '.' if group else ''
        chain.append(f'{prefix}{operation["operationId"]}Handler(serverCtx)')
        hertzpath = re.sub(r'\{(\w+)\}', r':\1', path)
        lines.append(f'\tserver.{method.upper()}("{hertzpath}", {", ".join(chain)})\n')
    lines.append('}\n')
    routes = ROOT / 'app/gateway/internal/handler/routes.go'
    routes.write_text(''.join(lines))
    subprocess.run(['gofmt', '-w', str(output), str(routes)], check=True)
    print(f'Generated {len(ids)} Hertz routes and {len(schemas)-1} DTOs')

if __name__ == '__main__':
    generate()
